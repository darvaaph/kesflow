import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const sql = readdirSync('supabase/migrations').filter((file) => file.endsWith('.sql')).sort()
  .map((file) => `-- Migration: ${file}\n${readFileSync(`supabase/migrations/${file}`, 'utf8')}`).join('\n\n');
writeFileSync('supabase_schema.sql', `-- Generated by npm run schema:build. For a NEW database only.\n${sql.trimEnd()}\n`);
